"""Generate embedded Jieba dictionaries as raw LZ4 blocks.

Run from any directory:
    python3 scripts/generate_jieba_embedded_dict.py

Requires a shared liblz4 on the generation host, supplied explicitly with
--lz4-library when it cannot be found automatically. Generated includes are
checked in, so normal and cross-platform builds do not run this script.
"""

from __future__ import annotations

import argparse
import ctypes
import ctypes.util
import hashlib
import logging
from pathlib import Path


def load_lz4(library_path: str | None):
    library_path = library_path or ctypes.util.find_library("lz4")
    if not library_path:
        raise RuntimeError("liblz4 not found; pass --lz4-library /path/to/liblz4")
    library = ctypes.CDLL(library_path)
    library.LZ4_versionNumber.argtypes = []
    library.LZ4_versionNumber.restype = ctypes.c_int
    library.LZ4_compressBound.argtypes = [ctypes.c_int]
    library.LZ4_compressBound.restype = ctypes.c_int
    library.LZ4_compress_HC.argtypes = [
        ctypes.c_void_p,
        ctypes.c_void_p,
        ctypes.c_int,
        ctypes.c_int,
        ctypes.c_int,
    ]
    library.LZ4_compress_HC.restype = ctypes.c_int
    library.LZ4_decompress_safe.argtypes = [
        ctypes.c_void_p,
        ctypes.c_void_p,
        ctypes.c_int,
        ctypes.c_int,
    ]
    library.LZ4_decompress_safe.restype = ctypes.c_int
    return library


def compress(library, original: bytes) -> bytes:
    if not original or len(original) > 0x7E000000:
        raise ValueError("dictionary must be nonempty and fit in an LZ4 block")
    source = ctypes.create_string_buffer(original)
    bound = library.LZ4_compressBound(len(original))
    destination = ctypes.create_string_buffer(bound)
    size = library.LZ4_compress_HC(source, destination, len(original), bound, 12)
    if size <= 0:
        raise RuntimeError("LZ4 compression failed")
    restored = ctypes.create_string_buffer(len(original))
    restored_size = library.LZ4_decompress_safe(
        destination, restored, size, len(original)
    )
    if restored_size != len(original) or restored.raw != original:
        raise RuntimeError("LZ4 round-trip verification failed")
    return destination.raw[:size]


def write_include(
    output: Path,
    symbol: str,
    source_name: str,
    original: bytes,
    compressed: bytes,
    lz4_version: int,
):
    with output.open("w", encoding="ascii", newline="\n") as stream:
        stream.write("// Generated by scripts/generate_jieba_embedded_dict.py.\n")
        stream.write(f"// Source: cppjieba-5.6.7/dict/{source_name}.\n")
        stream.write("// Source SHA-256:\n")
        stream.write(f"// {hashlib.sha256(original).hexdigest()}\n")
        stream.write(f"// Raw LZ4 block, HC level 12, liblz4 {lz4_version}.\n")
        stream.write("// clang-format off\n")
        stream.write(f"constexpr unsigned char {symbol}[] = {{\n")
        for offset in range(0, len(compressed), 16):
            chunk = compressed[offset : offset + 16]
            stream.write("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",\n")
        stream.write("};\n")
        stream.write(f"constexpr std::size_t {symbol}OriginalSize = {len(original)};\n")
        stream.write("// clang-format on\n")


def main():
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lz4-library", help="path to a shared liblz4")
    parser.add_argument(
        "--dict-dir",
        type=Path,
        default=root / "thirdparty/cppjieba/cppjieba-5.6.7/dict",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=root / "src/db/index/column/fts_column/tokenizer",
    )
    args = parser.parse_args()
    library = load_lz4(args.lz4_library)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for source_name, output_name, symbol in (
        ("jieba.dict.utf8", "jieba_dict_lz4.inc", "kJiebaDictLz4"),
        ("hmm_model.utf8", "jieba_hmm_model_lz4.inc", "kJiebaHmmModelLz4"),
    ):
        original = (args.dict_dir / source_name).read_bytes()
        compressed = compress(library, original)
        write_include(
            args.output_dir / output_name,
            symbol,
            source_name,
            original,
            compressed,
            library.LZ4_versionNumber(),
        )
        logging.info("%s: %d -> %d bytes", source_name, len(original), len(compressed))


if __name__ == "__main__":
    main()
