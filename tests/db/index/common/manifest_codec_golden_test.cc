//! Golden-byte and robustness tests for ManifestCodec.
//!
//! The byte arrays below pin the on-disk manifest format: decoding them must
//! yield the expected values and re-encoding must reproduce the exact same
//! bytes. All of them were produced by protobuf implementations:
//!
//! - kGoldenEmpty, kGoldenSimple and kGoldenAllIndexTypes were generated by
//!   the libprotobuf-based serializer zvec used before ManifestCodec existed.
//! - Every array in this file has additionally been reproduced byte-for-byte
//!   by an independent protobuf implementation compiled from the archived
//!   proto definition (src/db/proto/zvec.proto as it existed before it was
//!   removed), so none of the bytes are trusted blindly.
//!
//! These tests do not depend on libprotobuf, so they keep guarding format
//! compatibility after that dependency is dropped.
//!
//! Never regenerate these arrays to make a failing test pass: a mismatch means
//! the persisted format changed and existing collections would fail to open.

